(** The trail: the record of what was run, where, and against which
    subject.

    It is evidence, not content. It lives outside the repository, in
    `.math/`, and it is not carried in the version control - because
    the method adds no file to a project by inertia, and because the
    trail is regenerated by running the checks again. What the trail is
    for is not to be an archive: it is to be the thing that lets the
    method say what it knows and when it knew it.

    One line per check run. JSON, because the trail is read by a
    program and not by a person, and because a line format that is
    read by a program is a format and needs a parser - this one, by
    the library. *)

let trail_path (root : string) = Filename.concat root ".math/trail.jsonl"

let ensure_dir (root : string) =
  let dir = Filename.concat root ".math" in
  if not (Sys.file_exists dir) then Unix.mkdir dir 0o755

(** Append one result. The subject's digest travels with it: that is
    the binding, and without it the line would be a claim about a
    subject that may no longer exist. *)
let append (root : string) (e : Domain.evidence) : unit =
  ensure_dir root;
  let outcome =
    match e.outcome with
    | Domain.Verified -> "verified"
    | Domain.Falsified -> "falsified"
    | Domain.Unresolved -> "unresolved"
    | Domain.Refused -> "refused"
  in
  let json =
    `Assoc
      [ ("claim", `String e.claim.id);
        ("outcome", `String outcome);
        ("bound_to", `String e.bound_to);
        ( "reason",
          match e.reason with Some r -> `String r | None -> `Null );
        (* Seconds since the epoch. The trail is read by a program,
           and the program compares order, not dates. *)
        ("at", `String (Printf.sprintf "%.0f" (Unix.time ()))) ]
  in
  let channel = open_out_gen [ Open_append; Open_creat; Open_wronly ] 0o644 (trail_path root) in
  output_string channel (Yojson.Safe.to_string json);
  output_char channel '\n';
  close_out channel

(** Read the trail back. The newest line for a claim is the one that
    counts: an older run does not overrule a newer one, but a newer one
    does not overrule a subject that has since moved either - that is
    the binding's work, and it happens in [Verdict.state_of]. *)
let read (root : string) : Domain.evidence list =
  let path = trail_path root in
  if not (Sys.file_exists path) then []
  else
    let channel = open_in path in
    let rec lines acc =
      match input_line channel with
      | line -> lines (line :: acc)
      | exception End_of_file ->
          close_in channel;
          List.rev acc
    in
    lines []
    |> List.filter_map (fun line ->
           match Yojson.Safe.from_string line with
           | json -> (
               match json with
               | `Assoc pairs ->
                   let get name =
                     match List.assoc_opt name pairs with
                     | Some (`String s) -> Some s
                     | _ -> None
                   in
                   (match (get "claim", get "outcome", get "bound_to") with
                   | Some id, Some outcome, Some bound ->
                       let o =
                         match outcome with
                         | "verified" -> Domain.Verified
                         | "falsified" -> Domain.Falsified
                         | "unresolved" -> Domain.Unresolved
                         | "refused" -> Domain.Refused
                         | _ -> Domain.Unresolved
                       in
                       Some { Domain.claim = { id; subject = { text = ""; scope = [] }; check = ""; falsifier = ""; register = Domain.Undeclared; accepted = None }; outcome = o; bound_to = bound; reason = get "reason" }
                   | _ -> None)
               | _ -> None)
           | exception Yojson.Json_error _ -> None)
