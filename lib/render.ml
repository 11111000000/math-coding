      in
      Buffer.add_string buf commit_html;
      (* 3. scope — list of paths and decisions *)
      let scope_paths =
        top_object_list lines "scope"
        |> Option.map (List.map fst)
      in
      let scope_html =
        Option.value scope_paths ~default:[]
        |> render_quad
      in
      Buffer.add_string buf scope_html;
      (* 4. outcomes — list of {id, statement} *)
      (match top_object_list lines "outcomes" with
       | Some [] | None -> ()
       | Some pairs ->
           Buffer.add_string buf
             (render_yaml_object_list_section ~heading:"Outcomes"
                ~pairs));
      (* 5. obligations — list of {id, claim, ...}; verdict-pill
            cross-link uses the in-memory verdict map. *)
      (match top_object_list lines "obligations" with
       | Some [] | None -> ()
       | Some pairs ->
           Buffer.add_string buf
             (render_yaml_obligations_section ~heading:"Obligations"
                ~pairs ~verdict_by_id));
      (* 6. counterexample — block scalar preferred, scalar fallback *)
      let ce_html =
        match top_block lines "counterexample" with
        | Some s ->
            render_yaml_section ~heading:"Counter-example"
              ~body_md:s
        | None -> (
            match top_scalar lines "counterexample" with
            | Some s ->
                render_yaml_section ~heading:"Counter-example"
                  ~body_md:s
            | None -> "")
      in
      Buffer.add_string buf ce_html;
      (* 7. risk — block scalar preferred; if not block-scalar,
            fall back to the inline value (rare). *)
      let risk_html =
        match top_block lines "risk" with
        | Some s ->
            render_yaml_section ~heading:"Risk" ~body_md:s
        | None -> (
            match top_scalar lines "risk" with
            | Some s ->
                render_yaml_section ~heading:"Risk" ~body_md:s
            | None -> "")
      in
      Buffer.add_string buf risk_html;
      (* 8. relations — list of objects with one field each
            (e.g. `addresses: [..]`, `supersedes: [..]`). We
            produce one bullet per (kind, target) pair. *)
      (match top_object_list lines "relations" with
       | Some [] | None -> ()
| Some pairs ->
            let flat =
              List.concat_map
                (fun (kind, body_md) ->
                  let lines = String.split_on_char '\n' body_md in
                  let target_list =
                    List.filter_map
                      (fun l ->
                        let t = String.trim l in
                        if String.length t > 2
                           && String.sub t 0 2 = "- "
                        then
                          Some
                            (String.sub t 2 (String.length t - 2))
                        else None)
                      lines
                  in
                  List.map (fun t -> (kind, t)) target_list)
                pairs
            in
           if flat <> [] then begin
             let buf2 = Buffer.create 128 in
             Printf.bprintf buf2
               "<h2>Relations</h2>\n<ul class=\"mathc-decision-relations\">\n";
             List.iter
               (fun (kind, target) ->
                 Printf.bprintf buf2
                   "  <li><code>%s</code> &rarr; <code>%s</code></li>\n"
                   (html_escape kind) (html_escape target))
               flat;
             Buffer.add_string buf2 "</ul>\n";
             Buffer.add_string buf (Buffer.contents buf2)
           end);
      (* 9. axiom_link — list of axiom ids, rendered as cross-links *)
      (match top_string_list lines "axiom_link" with
       | Some [] | None -> ()
       | Some ids ->
           let axiom_links =
             List.map
               (fun id ->
                 Printf.sprintf "<a href=\"../axioms/%s.html\">%s</a>"
                   (html_escape id) (html_escape id))
               ids
           in
           let inline = String.concat " &middot; " axiom_links in
           Buffer.add_string buf
             (Printf.sprintf
                "<h2>Axiom links</h2>\n<p class=\"mathc-decision-axiom-link\">%s</p>\n"
                inline));
      Buffer.contents buf

(* Stubs the helpers `render_yaml_section` etc. above already
   defined. The `render_quad` placeholder that lived here was
   promoted to its own top-level binding near the section
   renderers. *)

let[@warning "-32"] render_spec_page ~name ~body_md =
  (* `spec/<name>.md` pages — normative algebra-3.2 spec, the
     constitution, the domain, the semantics. Each page is rendered
     with `enable_mathjax:true` so MathJax 3 (in defer mode) is
     injected into `<head>` and the page's `$..$` / `$$..$$`
     formulas are typeset as TeX at runtime. The class
     `mathc-spec-page` marks the wrapper so a future stylesheet
     can target math-heavy spec pages distinctly from prose site
     articles. *)
  let body_md_parsed = md_parse body_md in
  Printf.sprintf "<section class=\"mathc-spec-page\">\n%s\n</section>\n"
    body_md_parsed

let[@warning "-32"] render_axiom_page ~axiom_id ~body =
  (* If the source body starts with `# <title>`, strip that
     leading heading — the synthetic `<h1>Axiom <id></h1>` we
     emit is the only heading the page needs. Without this
     strip, every per-axiom page carries two `<h1>` (e.g. on
     `dist/axioms/feedback.html`: "Axiom feedback" from the
     template + "Axiom A1 — Feedback" from the source). *)
  let stripped_body =
    let trimmed = String.trim body in
    let len = String.length trimmed in
    if len > 2 && String.sub trimmed 0 2 = "# " then begin
      let prefix_len = 2 in
      let after_hash = String.sub trimmed prefix_len (len - prefix_len) in
      let nl_in_after =
        let s = String.length after_hash in
        let i = ref 0 in
        while !i < s && after_hash.[!i] <> '\n' do
          incr i
        done;
        if !i = s then s else !i
      in
      let first_line = String.sub after_hash 0 nl_in_after in
      (* `rest_start` is an offset into `trimmed`; convert it back to
         an offset into the original `body` by adding the leading
         whitespace count. *)
      let ws = ref 0 in
      while
        !ws < String.length body && (body.[!ws] = ' ' || body.[!ws] = '\n')
      do
        incr ws
      done;
      let rest_start_in_body = !ws + prefix_len + nl_in_after + 1 in
      let rest =
        if rest_start_in_body < String.length body then
          String.sub body rest_start_in_body
            (String.length body - rest_start_in_body)
        else ""
      in
      String.trim (Printf.sprintf "%s\n%s" first_line rest)
    end
    else body
  in
  Printf.sprintf
    "<section class=\"mathc-axiom-page\">\n\
     <h1>Axiom %s</h1>\n\
     <div>%s</div>\n\
     </section>\n"
    axiom_id (md_parse stripped_body)

