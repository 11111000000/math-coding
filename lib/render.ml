(* Read the project version from a `VERSION` file. The file is the
   single source of truth — release procedure writes it (or a
   pre-commit hook keeps it in sync with the latest `v*` tag). We
   try a small set of well-known paths because the CWD at module
   load time is not always the repo root (it is, in the `mathc
   render` invocation pattern; it is not, when the test harness
   loads the kernel from `_build/default/tests/`). The `fallback`
   argument is used when none of the candidates exist, so the
   kernel does not crash on a clean install where the share-dir
   VERSION is elsewhere. *)
let[@warning "-32"] read_version_file ~fallback =
  (* `dune test` exports the project root in `DUNE_SOURCEROOT`;
     honour it first so test runs and `mathc render` invocations
     agree on the same VERSION file. *)
  let dune_root =
    match Sys.getenv_opt "DUNE_SOURCEROOT" with
    | Some p -> Some (Filename.concat p "VERSION")
    | None -> None
  in
  let candidates =
    Option.to_list dune_root
    @ [
        "VERSION";
        "../VERSION";
        "../../VERSION";
        "../../../VERSION";
        "../../../../VERSION";
      ]
  in
  let try_one path =
    if Sys.file_exists path then begin
      let ic = open_in path in
      let n = in_channel_length ic in
      let s = really_input_string ic n in
      close_in ic;
      Some (s |> String.trim)
    end
    else None
  in
  let rec loop = function
    | [] -> fallback
    | p :: rest -> ( match try_one p with Some v -> v | None -> loop rest)
  in
  loop candidates

(* Read every `*.md` file under `spec/` and return them as
   (name, body) pairs sorted alphabetically. The dispatcher
   did not previously render spec files; this helper lets
   `build_pages` self-serve the spec source so a spec page
   lands under `dist/spec/<name>.html` with MathJax 3 in
   `<head>`, without requiring a dispatcher change. The read
   is best-effort: a missing `spec/` directory or unreadable
   file returns `[]`, matching `read_axioms` in `bin/Mathc.ml`.
   `DUNE_SOURCEROOT` is honoured first so a kernel test
   loaded from `_build/default/tests/` reads the same `spec/`
   that a `mathc render` invocation does. *)
let[@warning "-32"] read_spec_files () =
  let candidates =
    match Sys.getenv_opt "DUNE_SOURCEROOT" with
    | Some p -> [ Filename.concat p "spec" ]
    | None -> []
  in
  let candidates = candidates @ [ "spec" ] in
  let try_dir d =
    if not (Sys.file_exists d) then None
    else if not (Sys.is_directory d) then None
    else
      try
        Some
          (Sys.readdir d |> Array.to_list
          |> List.filter (fun n -> Filename.extension n = ".md")
          |> List.sort String.compare
          |> List.filter_map (fun n ->
              let base = Filename.chop_extension n in
              let path = Filename.concat d n in
              let ic = open_in_bin path in
              let n_bytes = in_channel_length ic in
              let s =
                if n_bytes = 0 then "" else really_input_string ic n_bytes
              in
              close_in ic;
              if s = "" then None else Some (base, s)))
      with _ -> None
  in
  let rec loop = function
    | [] -> []
    | d :: rest -> ( match try_dir d with Some xs -> xs | None -> loop rest)
  in
  loop candidates

(* Default version used when no VERSION file is present. Kept
   conservative — a render with an explicit version string
   (e.g., `v3.1.0-alpha`) is preferred so a viewer who lands on
   the site mid-release can tell which build is live. *)
let[@warning "-32"] default_version = "math-coding"

(* Build the per-language page list. The dispatcher is responsible
   for loading the article tuples from disk; this function only
   renders them. Tuple = (name, title, body_md). *)
let[@warning "-32"] build_pages ~package_html ~decisions_data ~policy_id ~config
    ~site_pages ~site_pages_ru ~axioms_data =
  let pages = ref [] in
  let version = config.version in

  (* Set of `name` keys that have a Russian sibling. Used by the
     language toggle to decide whether to emit `<name>.ru.html`
     link. Built from `site_pages_ru`, with `home` added when
     Russian is enabled (`index.ru.html` is generated
     unconditionally by the index renderer even though the
     article catalogue does not list a `home.ru.md`). *)
  let ru_keys =
    List.fold_left
      (fun acc (name, _, _) -> String_set.add name acc)
      String_set.empty site_pages_ru
  in
  let ru_keys =
    if List.mem "ru" config.languages then String_set.add "home" ru_keys
    else ru_keys
  in
  let has_ru name = String_set.mem name ru_keys in

  let render_lang_page lang (name, title, body_md) =
    let page_path = if lang = "ru" then name ^ ".ru.html" else name ^ ".html" in
    let page_title = title ^ " — math-coding" in
    let body_md_parsed = md_parse body_md in
    (* The `packages` page appends the live kernel package grid
       below the prose. The grid is the same HTML that
       `mathc packages --format=html` emits; embedding it here
       means `dist/packages.html` is no longer prose-only. *)
    let body_extra =
      if name = "packages" then
        Printf.sprintf
          "\n\
           <section class=\"mathc-packages-section\">\n\
           <h2>Packages</h2>\n\
           %s\n\
           </section>\n"
          package_html
      else ""
    in
    let body =
      Printf.sprintf "<article class=\"mathc-article\">\n%s%s\n</article>\n"
        body_md_parsed body_extra
    in
    {
      path = page_path;
      body =
        render_page ~lang ~page_key:name ~title:page_title ~body
          ~site_base:config.site_base ~enable_mathjax:config.enable_mathjax
          ~enable_mermaid:config.enable_mermaid
          ~enable_lang_toggle:config.enable_lang_toggle ~has_ru:(has_ru name)
          ~version ~extra_head:"";
    }
  in

  (* English index *)
  let axioms_overview_html = render_axioms_section axioms_data in
  let index_body_en =
    render_index ~package_html ~axioms_html:axioms_overview_html ~policy_id
      ~version
  in
  pages :=
    {
      path = "index.html";
      body =
        render_page ~lang:"en" ~page_key:"home"
          ~title:(Printf.sprintf "math-coding %s" version)
          ~body:index_body_en ~site_base:config.site_base
          ~enable_mathjax:config.enable_mathjax
          ~enable_mermaid:config.enable_mermaid
          ~enable_lang_toggle:config.enable_lang_toggle ~has_ru:(has_ru "home")
          ~version ~extra_head:"";
    }
    :: !pages;

  (* Russian index (only when Russian is enabled). *)
  if List.mem "ru" config.languages then begin
    let axioms_overview_html_ru = render_axioms_section axioms_data in
    let index_body_ru =
      render_index_ru ~package_html ~axioms_html:axioms_overview_html_ru
        ~policy_id ~version
    in
    pages :=
      {
        path = "index.ru.html";
        body =
          render_page ~lang:"ru" ~page_key:"home"
            ~title:(Printf.sprintf "math-coding %s" version)
            ~body:index_body_ru ~site_base:config.site_base
            ~enable_mathjax:config.enable_mathjax
            ~enable_mermaid:config.enable_mermaid
            ~enable_lang_toggle:config.enable_lang_toggle
            ~has_ru:(has_ru "home") ~version ~extra_head:"";
      }
      :: !pages
  end;

  (* Per-language articles. *)
  List.iter (fun t -> pages := render_lang_page "en" t :: !pages) site_pages;
  List.iter (fun t -> pages := render_lang_page "ru" t :: !pages) site_pages_ru;

  (* Per-decision pages (English-only). The body is built from
     two halves: the YAML narrative (intent / commitment / outcomes /
     obligations-with-claims / counter-example / risk / relations /
     scope / axiom-link) and the verdict grid. The narrative is
     rendered via `render_decision_yaml` which consumes the raw
     YAML body that the dispatcher passed through `decisions_data`;
     when the body is `None` (a decision file the kernel could not
     parse) the page falls back to title + verdict grid only. *)
  List.iter
    (fun (decision_id, ob_html, yaml_body) ->
      let verdict_by_id =
        ob_html
        |> (fun _ ->
            (* Build a map of obligation_id -> verdict from the
               package_list we received indirectly via `ob_html`.
               The verdict is encoded in the obligation HTML's
               class name (a mathc-verdict-NAME CSS class); we
               parse it from `ob_html` rather than threading a
               separate verdict list through `decisions_data`. *)
            let pat = "mathc-verdict-" in
            let lines = String.split_on_char '\n' ob_html in
            List.filter_map
              (fun l ->
                let id_pos =
                  let rec scan i =
                    if i + 3 >= String.length l then -1
                    else if String.sub l i 4 = "<cod"
                    then i + 4
                    else scan (i + 1)
                  in
                  scan 0
                in
                if id_pos < 0 then None
                else
                  let id_end = ref id_pos in
                  while !id_end < String.length l
                        && l.[!id_end] <> '<'
                  do
                    incr id_end
                  done;
                  let id =
                    String.sub l id_pos (!id_end - id_pos)
                  in
                  let verdict_pos =
                    let rec scan i =
                      if i >= String.length l - 16 then -1
                      else if String.sub l i 15 = pat then i + 15
                      else scan (i + 1)
                    in
                    scan 0
                  in
                  if verdict_pos < 0 then None
                  else
                    let verdict_end = ref verdict_pos in
                    while !verdict_end < String.length l
                          && l.[!verdict_end] <> '"'
                    do
                      incr verdict_end
                    done;
                    let verdict =
                      String.sub l verdict_pos
                        (!verdict_end - verdict_pos)
                    in
                    Some (id, verdict))
              lines)
      in
      let narrative_html = render_decision_yaml ~yaml_body ~verdict_by_id in
      let body =
        if narrative_html = "" then
          render_decision_page ~decision_id ~obligation_html:ob_html
        else
          Printf.sprintf
            "<section class=\"mathc-decision-page\">\n<h1>%s</h1>\n%s\n%s\n</section>\n"
            decision_id narrative_html ob_html
      in
      pages :=
        {
          path = Filename.concat "decisions" (decision_id ^ ".html");
          body =
            render_page ~lang:"en" ~page_key:"packages"
              ~title:(Printf.sprintf "%s — math-coding" decision_id)
              ~body ~site_base:config.site_base
              ~enable_mathjax:config.enable_mathjax
              ~enable_mermaid:config.enable_mermaid
              ~enable_lang_toggle:config.enable_lang_toggle ~has_ru:false
              ~version ~extra_head:"";
        }
        :: !pages)
    decisions_data;

  (* Per-axiom pages (English-only — body content is the same). *)
  List.iter
    (fun (axiom_id, body_md) ->
      let body = render_axiom_page ~axiom_id ~body:body_md in
      pages :=
        {
          path = Filename.concat "axioms" (axiom_id ^ ".html");
          body =
            render_page ~lang:"en" ~page_key:"axioms"
              ~title:(Printf.sprintf "Axiom %s" axiom_id)
              ~body ~site_base:config.site_base
              ~enable_mathjax:config.enable_mathjax
              ~enable_mermaid:config.enable_mermaid
              ~enable_lang_toggle:config.enable_lang_toggle ~has_ru:false
              ~version ~extra_head:"";
        }
        :: !pages)
    axioms_data;

  (* Per-spec pages (English-only). The spec source under `spec/`
     is normative (algebra-3.2, constitution, domain, semantics);
     each page is forced to `enable_mathjax:true` regardless of
     `config.enable_mathjax` so MathJax 3 is always available for
     `$..$` / `$$..$$` formulas at runtime. Reading `spec/*.md`
     here — rather than in `bin/Mathc.ml` — keeps `lib/render.ml`
     self-contained: the spec surface lands under
     `dist/spec/<name>.html` whenever `mathc render` runs, without
     the dispatcher learning about spec pages. *)
  let spec_data = read_spec_files () in
  List.iter
    (fun (name, body_md) ->
      let body = render_spec_page ~name ~body_md in
      pages :=
        {
          path = Filename.concat "spec" (name ^ ".html");
          body =
            render_page ~lang:"en" ~page_key:("spec/" ^ name)
              ~title:(Printf.sprintf "%s — math-coding spec" name)
              ~body ~site_base:config.site_base ~enable_mathjax:true
              ~enable_mermaid:config.enable_mermaid
              ~enable_lang_toggle:config.enable_lang_toggle ~has_ru:false
              ~version ~extra_head:"";
        }
        :: !pages)
    spec_data;

  List.rev !pages

(* Default configuration used by the CLI. The dispatcher overrides
   from CLI flags. *)
let[@warning "-32"] default_config =
  {
      site_base = "/math-coding/";
    (* MathJax 3 defaults ON. The previous default-OFF workaround
       in `render-kernel-fixes-2026-10@1` (`mathjax-default-off`,
       assumption `mathjax-off-default-is-acceptable`) is retired:
       the `$` is no longer an active math delimiter thanks to
       `mathjax-delimiter-hardening-2026-10@1`, which narrowed the
       configuration to LaTeX-only (`\(..\)` / `\[..\]`). A stray
       `$` in prose is a literal character even when MathJax is
       on. The script tag is therefore emitted on every page
       (prose + axiom + spec) by default; pages that need
       MathJax off opt out via the `--no-mathjax` CLI flag or by
       setting `Render.config.enable_mathjax = false`
       programmatically. *)
    enable_mathjax = true;
    enable_mermaid = true;
    enable_lang_toggle = true;
    languages = [ "en" ];
    (* Default version reads from `./VERSION` at render time. The
       CLI dispatcher overrides this with whatever the current
       working directory's VERSION file holds, so a site deployed
       from a freshly-cut release tag carries the right version
       automatically. The string here is a last-resort fallback
       for callers that bypass the CLI. *)
    version = read_version_file ~fallback:default_version;
  }
