(* The site is served at /math-coding/ on GitHub Pages.
   Relative hrefs like "/manifesto.html" would resolve to
   "<user>.github.io/manifesto.html" (without /math-coding/),
   causing 404. The <base> tag fixes this for all relative URLs
   in the document. Override via MATH_CODING_BASE env if needed. *)
let site_base =
  match Sys.getenv_opt "MATH_CODING_BASE" with
  | Some "" -> "/math-coding/"
  | Some s -> s
  | None -> "/math-coding/"

