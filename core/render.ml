let render_supersession_graph packets =
  let lines = ref ["graph LR"; "  %% supersession chains"] in
  List.iter
    (fun (older, newer) ->
      let older_clean = String.map (fun c -> if c = '/' || c = '-' then '_' else c) older in
      let newer_clean = String.map (fun c -> if c = '/' || c = '-' then '_' else c) newer in
      lines := Printf.sprintf "  %s --> %s" older_clean newer_clean :: !lines)
    packets;
  mermaid_wrapper (String.concat "\n" (List.rev !lines))

